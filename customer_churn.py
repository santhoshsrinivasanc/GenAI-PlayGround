import pandas as pd
import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense

#Dataset creation
np.random.seed(42)
tenure = np.random.randint(1,60,1000)
monthly_charges = np.random.uniform(20,120,1000)
data_usage = np.random.randint(1,60,1000)
support_tickets = np.random.randint(0,10,1000)

#Churn rule
churn = ((tenure < 12) & (support_tickets > 3)) | (monthly_charges > 100)
churn = churn.astype(int)

#DataFrame creation
df = pd.DataFrame({
    'Tenure': tenure,
    'Monthly charges' : monthly_charges,
    'Data usage' : data_usage,
    'Support ticket' : support_tickets,
    'Churn' : churn
})

#Input values
X = df[['Tenure','Monthly charges', 'Data usage', 'Support ticket']]
Y = df['Churn']
print(df['Churn'].value_counts())

#Training and testing
X_train,X_test,Y_train,Y_test = train_test_split(X,Y,test_size=0.2,random_state=42)

#Scaling
scaler = StandardScaler()
X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

#ANN model
model = Sequential([
    Dense(16,activation= 'relu', input_shape = (4,)),
    Dense(8,activation='relu'),
    Dense(1,activation='sigmoid')
])

#Compile model
model.compile(optimizer = 'adam' , loss = 'binary_crossentropy' , metrics = ['accuracy'])

#Summary
model.summary()

#Model training

history = model.fit(X_train, Y_train, epochs = 100, batch_size = 32 , validation_split = 0.2 , verbose = 1)

#Model evaluation
loss, acc = model.evaluate(X_test,Y_test)
print('Loss : ',loss)
print('Accuracy : ',acc)

#New customer input to predict
customer = pd.DataFrame([[12,200,110,5]],
columns = ['Tenure', 'Monthly charges', 'Data usage', 'Support ticket'])
customer_scaled = scaler.transform(customer)
prediction = model.predict(customer_scaled)
print('\nChurn Probability : ',prediction[0][0])
print('Predicted churn : ','Yes' if prediction[0][0]>0.5 else 'No')

#Visualization
plt.figure(figsize=(8,5))
plt.plot(history.history['loss'] ,label = 'Training loss')
plt.plot(history.history['val_loss'], label = 'Vaidation loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.title('ANN LOSS CURVE')
plt.legend()
plt.grid()
plt.show()