TEST_TICKETS = [
    "My payment failed while purchasing an item.",
    "I was charged twice for my order.",
    "The application keeps crashing.",
    "I want my money back.",
    "How can I return my product?",
    "Do you have any discounts available?",
    "I paid but the app froze and now I want the money returned",  # tricky, multi-issue
]


def main():
    import os
    print("Choose approach:\n  1. Rule-based\n  2. Embeddings\n  3. LLM (Claude)")
    choice = input("Enter 1, 2 or 3: ").strip()

    if choice == "1":
        router = RuleBasedRouter()
    elif choice == "2":
        router = EmbeddingRouter()
    elif choice == "3":
        if not os.getenv("ANTHROPIC_API_KEY"):
            raise SystemExit("Set the ANTHROPIC_API_KEY environment variable first.")
        router = LLMRouter()
    else:
        raise SystemExit("Invalid choice.")

    for ticket in TEST_TICKETS:
        result = router.route_ticket(ticket)
        print(f"\nTicket     : {ticket}")
        print(f"Routed to  : {result['team']}  ({result['confidence']:.0%})")
        print(f"Details    : {result['details']}")

    print("\nType your own ticket ('exit' to quit).")
    while True:
        ticket = input("\nTicket: ").strip()
        if ticket.lower() == "exit":
            break
        if ticket:
            result = router.route_ticket(ticket)
            print(f"Routed to {result['team']} ({result['confidence']:.0%}) | {result['details']}")


if __name__ == "__main__":
    main()