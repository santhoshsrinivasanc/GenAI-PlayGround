#APPROACH 1: RULE-BASED (weighted phrases, lemma aware)
# ============================================================
class RuleBasedRouter:
    """Each phrase has a weight. Strong phrases ('money back') beat weak ones ('card')."""

    RULES = {
        "Billing Team": {"charged twice": 3, "payment failed": 3, "declined": 2,
                         "charge": 2, "payment": 2, "invoice": 2, "billing": 2,
                         "transaction": 2, "card": 1},
        "Technical Team": {"login": 3, "log in": 3, "password": 3, "crash": 3,
                           "error": 2, "bug": 2, "not work": 2, "not open": 2,
                           "website": 1, "app": 1},
        "Refund Team": {"refund": 4, "money back": 4, "return": 3,
                        "cancel order": 2, "send back": 2},
        "Sales Team": {"price": 3, "discount": 3, "offer": 2, "buy": 3,
                       "purchase": 2, "stock": 2, "product": 1},
    }

    def __init__(self):
        import spacy
        from spacy.matcher import PhraseMatcher

        self.nlp = spacy.load("en_core_web_sm")
        # Match on lemmas so "crashing" -> "crash", "charged" -> "charge"
        self.matcher = PhraseMatcher(self.nlp.vocab, attr="LEMMA")
        self.weights = {}
        for team, phrases in self.RULES.items():
            for phrase, weight in phrases.items():
                key = f"{team}|{phrase}"
                self.matcher.add(key, [self.nlp(phrase)])
                self.weights[key] = weight

    def route_ticket(self, ticket: str) -> dict:
        from collections import defaultdict
        doc = self.nlp(ticket.lower())
        scores = defaultdict(int)
        hits = defaultdict(list)
        for match_id, start, end in self.matcher(doc):
            key = self.nlp.vocab.strings[match_id]
            team, phrase = key.split("|")
            scores[team] += self.weights[key]
            hits[team].append(doc[start:end].text)

        if not scores:
            return {"team": "General Support", "confidence": 0.0, "details": {}}

        total = sum(scores.values())
        best = max(scores, key=scores.get)
        return {"team": best, "confidence": scores[best] / total, "details": dict(hits)}



