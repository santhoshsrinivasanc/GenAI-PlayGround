# APPROACH 3: LLM (Claude via Anthropic API)
# ============================================================
class LLMRouter:
    """Best for long, messy or multi-issue tickets. Needs internet + API key."""

    SYSTEM = (
        "You route customer support tickets. Teams: "
        + ", ".join(TEAMS)
        + ", General Support. Reply ONLY with JSON: "
        '{"team": "", "confidence": <0-1>, "reason": ""}'
    )

    def __init__(self, model="claude-sonnet-5-5"):
        import anthropic

        self.client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY
        self.model = model

    def route_ticket(self, ticket: str) -> dict:
        response = self.client.messages.create(
            model=self.model,
            max_tokens=200,
            system=self.SYSTEM,
            messages=[{"role": "user", "content": ticket}],
        )
        text = response.content[0].text.strip().replace("```json", "").replace("```", "")
        try:
            data = json.loads(text)
        except json.JSONDecodeError:
            return {"team": "General Support", "confidence": 0.0, "details": text}
        return {
            "team": data.get("team", "General Support"),
            "confidence": float(data.get("confidence", 0)),
            "details": data.get("reason", ""),
        }


