# APPROACH 2: SENTENCE EMBEDDINGS (semantic search)
# ============================================================
class EmbeddingRouter:
    """Embeds every example once, then compares each ticket against all of them."""

    def __init__(self, model_name="all-MiniLM-L6-v2", threshold=0.35):
        from sentence_transformers import SentenceTransformer, util

        self.util = util
        self.model = SentenceTransformer(model_name)
        self.threshold = threshold
        self.labels, sentences = [], []
        for team, examples in EXAMPLES.items():
            for sentence in examples:
                self.labels.append(team)
                sentences.append(sentence)
        self.embeddings = self.model.encode(sentences, convert_to_tensor=True)

    def route_ticket(self, ticket: str) -> dict:
        from collections import defaultdict
        query = self.model.encode(ticket, convert_to_tensor=True)
        sims = self.util.cos_sim(query, self.embeddings)[0].tolist()

        # Per team: average of its top-2 most similar examples
        per_team = defaultdict(list)
        for label, sim in zip(self.labels, sims):
            per_team[label].append(sim)
        scores = {t: sum(sorted(v, reverse=True)[:2]) / 2 for t, v in per_team.items()}

        best = max(scores, key=scores.get)
        if scores[best] < self.threshold:
            best = "General Support"
        return {"team": best, "confidence": max(scores.values()), "details": scores}



